-- Sửa <mật khẩu> và tablespace trước khi chạy. Chỉ dùng cho môi trường test.
CREATE USER RECON_SRC IDENTIFIED BY "<mật khẩu>"
  DEFAULT TABLESPACE USERS QUOTA 1G ON USERS;
GRANT CREATE SESSION, CREATE TABLE TO RECON_SRC;

CREATE USER RECON_SRC_RO IDENTIFIED BY "<mật khẩu>";
GRANT CREATE SESSION TO RECON_SRC_RO;

CREATE TABLE RECON_SRC.SRC_FACT_INVOICE_DTP (
  INVOICE_NO      VARCHAR2(30)  NOT NULL,
  INVOICE_DATE    DATE          NOT NULL,
  COLLECT_POINT   VARCHAR2(20),
  TXN_ID          VARCHAR2(80),
  PIN_NO          VARCHAR2(30),
  SERVICE_CODE    VARCHAR2(10),
  QUANTITY        NUMBER(12,2),
  AMOUNT          NUMBER(18,2),
  INVOICE_STATUS  VARCHAR2(20),
  ORG_CODE        VARCHAR2(10)
);
CREATE INDEX RECON_SRC.IX_SRC_DTP_DATE ON RECON_SRC.SRC_FACT_INVOICE_DTP (INVOICE_DATE, ORG_CODE);

GRANT SELECT ON RECON_SRC.SRC_FACT_INVOICE_DTP TO RECON_SRC_RO;
